#!/usr/bin/env bash
# Renders the complete testnet Caddyfile to stdout.
#
# Single source of the Caddyfile: update-caddy.yml deploys this output and CI
# runs `caddy validate` on it with the pinned caddy-ratelimit image.
#
# Usage: scripts/render-caddyfile.sh <tfvars-file>
# Env (required): NODE_API_KEY     main node REST API key injected for /peers/* reads
#                 E2E_BYPASS_KEY   secret header value that exempts admin-e2e traffic
#                 SELF_IP          the VPS public IPv4; its own hairpin calls (scanner
#                                  SSR, exporter probes) are exempt from per-IP limits
set -euo pipefail

TFVARS="${1:?usage: render-caddyfile.sh <tfvars-file>}"
: "${NODE_API_KEY:?NODE_API_KEY must be set}"
: "${E2E_BYPASS_KEY:?E2E_BYPASS_KEY must be set}"
: "${SELF_IP:?SELF_IP must be set}"

parse() { grep "^${1}" "${TFVARS}" | awk -F'"' '{print $2}'; }
SCANNER=$(parse scanner_domain)
DATA_SVC=$(parse data_service_domain)
WEBSOCKET=$(parse websocket_domain)
NODE=$(parse node_domain)
MATCHER=$(parse matcher_domain)
ADMIN=$(parse admin_domain)
GRAFANA=$(parse grafana_domain)
ACME=$(parse acme_email)
for v in SCANNER DATA_SVC WEBSOCKET NODE MATCHER ADMIN ACME; do
  [[ -n "${!v}" ]] || { echo "render-caddyfile: ${v} missing from ${TFVARS}" >&2; exit 1; }
done

cat <<EOF
# Generated by scripts/render-caddyfile.sh (deployed by update-caddy.yml) — do not edit manually
{
    admin unix//run/caddy/admin.sock
    email ${ACME}
}
# Shared CORS origin allowlist for credentialed endpoints (node, matcher).
# Reflecting Origin unconditionally alongside Allow-Credentials: true lets
# any website make authenticated cross-origin requests on a visitor's
# behalf (CWE-942) — @cors_allowed_origin matches the three domains the
# actual first-party apps are deployed under: decentralchain.io (data
# service, websocket, admin), decentralscan.com (scanner — its own
# scanner_domain in testnet.tfvars is testnet.decentralscan.com, NOT a
# decentralchain.io subdomain), and decentral.exchange (exchange, deployed
# via Cloudflare Pages — see DecentralChain's deploy-exchange.yml). Missing
# the latter two meant every scanner/exchange page load got zero CORS
# headers back from the node/matcher, silently failing every direct
# client-side fetch (empty height/version/last-block on the scanner's
# Network Overview, confirmed live 2026-08-13).
(cors_allowlist) {
    @cors_allowed_origin header_regexp Origin ^https://([a-z0-9-]+\.)?(decentralchain\.io|decentralscan\.com|decentral\.exchange)$
}

# Access logs (shipped to Loki by alloy) must never carry credentials. Caddy logs
# request headers verbatim, so X-Api-Key and the X-E2E-Bypass rate-limit key were
# stored in Loki in plaintext (2026-10-18 audit). Header names are logged in Go's
# canonical form, hence X-E2e-Bypass.
(redacted_log) {
    log {
        format filter {
            wrap json
            fields {
                request>headers>X-Api-Key delete
                request>headers>X-E2e-Bypass delete
                request>headers>Authorization delete
                request>headers>Cookie delete
            }
        }
    }
}

${SCANNER} {
    handle /api/geo/* {
        uri strip_prefix /api/geo
        reverse_proxy https://ipinfo.io {
            header_up Host ipinfo.io
            # Strip upstream headers that should not be forwarded to the browser
            header_down -Alt-Svc
            header_down -Access-Control-Allow-Origin
            header_down -Via
        }
    }
    handle /api/greencheck/* {
        uri replace /api/greencheck /api/v3/greencheck
        reverse_proxy https://api.thegreenwebfoundation.org {
            header_up Host api.thegreenwebfoundation.org
            header_down -Alt-Svc
            header_down -Via
        }
    }
    # Faucet abuse control (SEC-3): strict per-IP limit at the edge — persistent
    # (survives scanner container restarts, unlike the app's in-memory 24h/address
    # limiter) and IP-scoped, so one host can't script-drain the faucet across many
    # addresses. 5 requests/hour/IP is ample for legitimate testers.
    @faucet path /api/faucet
    rate_limit @faucet {
        zone faucet_per_ip {
            key    {remote_host}
            events 5
            window 1h
        }
    }
    reverse_proxy 127.0.0.1:3000 {
        header_up X-Real-IP {remote_host}
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        X-Frame-Options "DENY"
        Referrer-Policy "strict-origin-when-cross-origin"
        X-XSS-Protection "0"
        Content-Security-Policy "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https:; font-src 'self' data:; connect-src 'self' https://*.decentralchain.io wss://*.decentralchain.io https://ipinfo.io https://api.thegreenwebfoundation.org; worker-src 'self' blob:; frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'"
        Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
        Cross-Origin-Opener-Policy "same-origin"
        -Server
    }
    encode gzip zstd
    import redacted_log
}

${DATA_SVC} {
    # data-service rate-limits by X-Real-IP, so Caddy sets it from the TCP peer
    # (header_up below); a client-supplied value is overwritten. The edge limit
    # is per TCP peer. The VPS's own hairpin calls (scanner SSR, exporter
    # probes) and admin-e2e traffic are exempt.
    # NOTE: this zone passes 300 req/min per peer (verified with the pinned
    # caddy-ratelimit image: 300 x 200, then 429). The observed ~120/min comes
    # from data-service's own in-process limiter (createRateLimiter max 120 per
    # 60 s, keyed by X-Real-IP; DecentralChain apps/data-service/src/index.ts),
    # which is tighter. The effective limit is therefore 120/min; this edge
    # zone is the backstop. Raising it is a data-service change, not a Caddy one.
    @ds_limited {
        not remote_ip ${SELF_IP} 127.0.0.1 ::1
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @ds_limited {
        zone ds_per_ip {
            key    {remote_host}
            events 300
            window 1m
        }
    }
    reverse_proxy 127.0.0.1:8080 {
        header_up X-Real-IP {remote_host}
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
        -Server
    }
    encode gzip zstd
    import redacted_log
}

${WEBSOCKET} {
    # One request per WebSocket connection (upgrade), so this caps new
    # connections per peer IP; subscriptions ride the open connection.
    @ws_limited {
        not remote_ip ${SELF_IP} 127.0.0.1 ::1
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @ws_limited {
        zone ws_per_ip {
            key    {remote_host}
            events 60
            window 1m
        }
    }
    reverse_proxy 127.0.0.1:8081 {
        header_up X-Real-IP {remote_host}
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
        -Server
    }
    import redacted_log
}

${NODE} {
    import cors_allowlist

    # -- Rate limiting -------------------------------------------------------
    # Requires the custom image built by build-caddy-ratelimit.yml (stock
    # caddy:*-alpine doesn't ship github.com/mholt/caddy-ratelimit). Verified
    # locally: each zone below is isolated (a burst on one path doesn't
    # consume another path's budget) and correctly returns 429 once exhausted.
    #
    # X-E2E-Bypass exempts our own admin-e2e.yml test traffic: with ~20+
    # parallel e2e spec files each funding test accounts via one broadcast
    # apiece, legitimate CI traffic alone exceeds broadcast_per_ip's budget.
    # A secret header (not an IP allowlist -- GH Actions IPs are public and
    # shared) -- anyone without the exact header still gets fully rate
    # limited. See docs/comment in DecentralChain's env.ts for the client side.
    @blocks_path {
        path /blocks/*
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @blocks_path {
        zone blocks_per_ip {
            key    {remote_host}
            events 1000
            window 1m
        }
    }
    @broadcast {
        path /transactions/broadcast
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @broadcast {
        zone broadcast_per_ip {
            key    {remote_host}
            events 50
            window 1m
        }
    }
    @other_api {
        not path /blocks/* /transactions/broadcast
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @other_api {
        zone api_per_ip {
            key    {remote_host}
            events 300
            window 1m
        }
    }
    # RIDE compile/evaluate endpoints are CPU-bound and unauthenticated on the node — cap them far
    # tighter than the general 300/min so they can't be used as a cheap CPU-DoS. Both zones apply, so
    # the effective limit is the tighter one.
    @utils_script {
        path /utils/script/*
        not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    }
    rate_limit @utils_script {
        zone utils_script_per_ip {
            key    {remote_host}
            events 30
            window 1m
        }
    }

    @options method OPTIONS
    handle @options {
        # Reflect origin only if it's on the allowlist (see @cors_allowed_origin
        # above) — required when the exchange sends credentials (cookies/auth).
        # Vary tells caches this header varies. No match = no CORS headers at
        # all, so the browser correctly refuses to expose the response.
        header @cors_allowed_origin Access-Control-Allow-Origin {http.request.header.Origin}
        header @cors_allowed_origin Access-Control-Allow-Credentials "true"
        header @cors_allowed_origin Access-Control-Allow-Methods "GET, POST, PUT, DELETE, OPTIONS"
        header @cors_allowed_origin Access-Control-Allow-Headers "Content-Type, Authorization, Accept, X-API-Key, timestamp, signature"
        header @cors_allowed_origin Access-Control-Max-Age "3600"
        header Vary "Origin"
        respond "" 204
    }
    # Inject the node API key ONLY for the specific read-only peer endpoints the
    # explorer/admin need. Do NOT key-inject the whole /debug/* or /consensus/*
    # namespaces: /debug/* includes destructive/heavy endpoints (rollback, print,
    # state, configInfo) that must never be publicly reachable, and POST /peers/*
    # (connect, clearblacklist) must not be callable either. Everything outside
    # this matcher falls through to the un-keyed proxy below, so the node's own
    # api-key auth returns 403 for protected routes.
    # -- Defense-in-depth denylist -------------------------------------------
    # Hard-404 the endpoints that must NEVER be public, regardless of the node's
    # own api-key auth, so a single blank/mis-set api-key-hash cannot expose them.
    # These are admin/secret/destructive; the explorer and DEX never call them.
    # GET reads (balances, blocks, tx info) and POST /transactions/broadcast are
    # deliberately NOT matched here.
    @admin_paths path /debug/* /wallet/* /node/stop /addresses/seed/*
    handle @admin_paths {
        respond "Not found" 404
    }
    @admin_sign {
        method POST
        path /transactions/sign /transactions/sign/*
    }
    handle @admin_sign {
        respond "Not found" 404
    }
    @admin_peers_write {
        method POST
        path /peers/connect /peers/clearblacklist
    }
    handle @admin_peers_write {
        respond "Not found" 404
    }
    @wallet_write {
        method POST DELETE PUT
        path /addresses /addresses/*
    }
    handle @wallet_write {
        respond "Not found" 404
    }

    @protected {
        method GET
        path /peers/connected /peers/all /peers/blacklisted /peers/suspended
    }
    handle @protected {
        reverse_proxy 127.0.0.1:6869 {
            header_up X-Real-IP {remote_host}
            header_up X-API-Key "${NODE_API_KEY}"
            header_up -Origin
            header_up -Referer
        }
        header {
            Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
            Vary "Origin"
            -Server
        }
        header @cors_allowed_origin Access-Control-Allow-Origin {http.request.header.Origin}
        header @cors_allowed_origin Access-Control-Allow-Credentials "true"
    }
    reverse_proxy 127.0.0.1:6869 {
        header_up X-Real-IP {remote_host}
        header_up -Origin
        header_up -Referer
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
        Vary "Origin"
        -Server
    }
    header @cors_allowed_origin Access-Control-Allow-Origin {http.request.header.Origin}
    header @cors_allowed_origin Access-Control-Allow-Credentials "true"
    import redacted_log
}

${MATCHER} {
    import cors_allowlist

    # -- Rate limiting (matcher) ----------------------------------------------
    # Same custom image requirement as NODE_DOMAIN above. Same X-E2E-Bypass
    # exemption as NODE_DOMAIN -- see the comment there.
    @rate_limited not header X-E2E-Bypass ${E2E_BYPASS_KEY}
    rate_limit @rate_limited {
        zone matcher_per_ip {
            key    {remote_host}
            events 300
            window 1m
        }
    }

    @options method OPTIONS
    handle @options {
        # timestamp and signature are custom headers sent by the exchange DEX client.
        # Origin reflected only if it's on the allowlist (@cors_allowed_origin above).
        header @cors_allowed_origin Access-Control-Allow-Origin {http.request.header.Origin}
        header @cors_allowed_origin Access-Control-Allow-Credentials "true"
        header @cors_allowed_origin Access-Control-Allow-Methods "GET, POST, PUT, DELETE, OPTIONS"
        header @cors_allowed_origin Access-Control-Allow-Headers "Content-Type, Authorization, Accept, timestamp, signature, X-API-Key"
        header @cors_allowed_origin Access-Control-Max-Age "3600"
        header Vary "Origin"
        respond "" 204
    }
    reverse_proxy 127.0.0.1:6886 {
        header_up X-Real-IP {remote_host}
        header_up -Origin
        header_up -Referer
        # The matcher itself answers Access-Control-Allow-Origin: *. Together with the
        # allowlisted origin reflected below, browsers got TWO values and rejected every
        # matcher call, so DEX trading on the exchange and the scanner's DEX Pairs page
        # were dead (2026-10-18 audit). Caddy is the single CORS authority here.
        header_down -Access-Control-Allow-Origin
        header_down -Access-Control-Allow-Credentials
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
        Vary "Origin"
        -Server
    }
    header @cors_allowed_origin Access-Control-Allow-Origin {http.request.header.Origin}
    header @cors_allowed_origin Access-Control-Allow-Credentials "true"
    import redacted_log
}

# Caddy metrics for the local Prometheus (monitoring/prometheus.yml job caddy). The admin API is a unix
# socket, so the metrics handler gets its own loopback-only plain-HTTP site. No access log (scraped every 30s).
http://127.0.0.1:2020 {
    bind 127.0.0.1
    metrics
}

${ADMIN} {
    reverse_proxy 127.0.0.1:3001 {
        header_up X-Real-IP {remote_host}
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        X-Frame-Options "DENY"
        Referrer-Policy "strict-origin-when-cross-origin"
        -Server
    }
    encode gzip zstd
    import redacted_log
}

EOF

if [[ -n "${GRAFANA}" ]]; then
cat <<EOF
${GRAFANA} {
    # Grafana runs on this VPS (compose/grafana.yml, port 3002); the
    # cluster has no Grafana. No X-Frame-Options, so the admin
    # dashboard can embed it in an iframe.
    # Grafana's /metrics is for the local Prometheus only (job grafana, loopback).
    respond /metrics 404
    reverse_proxy 127.0.0.1:3002 {
        header_up X-Real-IP {remote_host}
    }
    header {
        Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
        # Only the admin dashboard may frame Grafana (its Operations page embeds it).
        Content-Security-Policy "frame-ancestors https://${ADMIN}"
        -Server
    }
    encode gzip zstd
    import redacted_log
}
EOF
fi
